"""站点 Cookie 管理（DR-39：唤起浏览器引导登录，捕获并缓存 Cookie）。

交互流程（用户视角）：
  1. 处理需登录站点时，自动弹出系统浏览器窗口（playwright channel 复用本机
     Edge/Chrome，无需下载浏览器内核）
  2. 用户在窗口内登录目标站点
  3. 程序自动捕获目标域关键 Cookie，存 Netscape 格式到 <data>/cookies/<site>.txt
  4. 后续访问同站点自动带 Cookie（yt-dlp --cookies）；失效时重新引导登录

设计要点：
- Netscape format（yt-dlp --cookies 原生支持）
- 登录检测：轮询目标域关键 Cookie（SESSDATA/sessionid 等）出现即成功
- 用户关闭浏览器或超时 → 返回 None（不阻塞主流程，站点仍可无 Cookie 尝试）
"""

from __future__ import annotations

import time
from pathlib import Path

from zhiying.envkeys import getenv  # noqa: F401  (统一配置读取)
from zhiying.paths import data_root

# 各站点登录态特征 Cookie 与登录入口
SITE_PROFILES = {
    "bilibili": {
        "login_url": "https://passport.bilibili.com/login",
        "check_domain": ".bilibili.com",
        "key_cookie": "SESSDATA",
    },
    "douyin": {
        "login_url": "https://www.douyin.com/login",
        "check_domain": ".douyin.com",
        "key_cookie": "sessionid",
    },
    "xiaohongshu": {
        "login_url": "https://www.xiaohongshu.com",
        "check_domain": ".xiaohongshu.com",
        "key_cookie": "web_session",
    },
    "weibo": {
        "login_url": "https://weibo.com/login",
        "check_domain": ".weibo.com",
        "key_cookie": "SUB",
    },
}


def cookies_dir() -> Path:
    d = data_root() / "cookies"
    d.mkdir(parents=True, exist_ok=True)
    return d


def cookie_file_for(site: str) -> Path:
    return cookies_dir() / f"{site}.txt"


def has_cookie(site: str) -> bool:
    """该站点是否已有缓存 Cookie（文件存在且大于头部长度）。"""
    f = cookie_file_for(site)
    return f.exists() and f.stat().st_size > 50


def site_for_url(url: str) -> str | None:
    """URL → 站点名（选 Cookie 文件与登录引导）。"""
    for site, prof in SITE_PROFILES.items():
        if prof["check_domain"].lstrip(".") in url:
            return site
    return None


def capture_cookies_interactive(site: str, timeout_sec: int = 300) -> Path | None:
    """弹出可见浏览器引导登录，捕获 Cookie 后存 Netscape 格式。

    返回 Cookie 文件路径（成功）或 None（用户关闭/超时/未登录成功）。
    channel 优先复用本机 Edge（无需下载浏览器内核），失败降级 playwright chromium。
    """
    prof = SITE_PROFILES.get(site)
    if not prof:
        print(f"⚠ 不支持的站点: {site}")
        return None
    try:
        from playwright.sync_api import sync_playwright
    except ImportError:
        print("⚠ playwright 未安装（可选组件）：pip install playwright")
        return None

    captured_cookies: list[dict] = []
    captured = False
    with sync_playwright() as pw:
        try:
            browser = pw.chromium.launch(headless=False, channel="msedge")
        except Exception:  # noqa: BLE001  本机无 Edge 时降级内置 chromium
            browser = pw.chromium.launch(headless=False)
        ctx = browser.new_context()
        page = ctx.new_page()
        page.goto(prof["login_url"])
        print(f"ℹ 已打开浏览器，请在窗口中登录 {site}（登录成功后自动捕获，最长等待 {timeout_sec}s）")

        deadline = time.time() + timeout_sec
        while time.time() < deadline:
            try:
                cookies = ctx.cookies()
                captured_cookies = cookies  # 持续快照
                hit = any(
                    c.get("domain", "").endswith(prof["check_domain"]) and c.get("name") == prof["key_cookie"]
                    for c in cookies
                )
                if hit:
                    captured = True
                    break
            except Exception:  # noqa: BLE001  页面跳转中读取可能暂时失败
                pass
            if page.is_closed():
                break
            time.sleep(2)
        try:
            ctx.close()
            browser.close()
        except Exception:  # noqa: BLE001
            pass

    if not captured:
        print(f"⚠ {site} 登录未完成（超时或窗口被关闭），本次不带 Cookie")
        return None
    return export_netscape(site, captured_cookies)


def export_netscape(site: str, cookies: list[dict]) -> Path | None:
    """playwright cookies → Netscape format（yt-dlp --cookies 原生格式）。"""
    prof = SITE_PROFILES.get(site)
    if not prof:
        return None
    lines = ["# Netscape HTTP Cookie File", "# Generated by zhiying", ""]
    for c in cookies:
        domain = c.get("domain", "")
        if not domain.endswith(prof["check_domain"]):
            continue
        flag = "TRUE" if domain.startswith(".") else "FALSE"
        path = c.get("path", "/")
        secure = "TRUE" if c.get("secure") else "FALSE"
        expire = str(int(c.get("expires") or 2147483647))
        lines.append("\t".join([domain, flag, path, secure, expire, c.get("name", ""), c.get("value", "")]))
    if len(lines) <= 3:
        return None
    f = cookie_file_for(site)
    f.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return f


def ytdlp_cookie_args(url: str) -> list[str]:
    """按 URL 匹配站点；有缓存 Cookie 时返回 yt-dlp 参数（无则空列表）。"""
    site = site_for_url(url)
    if site and has_cookie(site):
        return ["--cookies", str(cookie_file_for(site))]
    return []
